// H3 returns latitude/longitude; native Polygon coordinates use longitude/latitude.
export const NYC_AFTER_DARK_SQL = `WITH
    geoToH3(assumeNotNull(pickup_latitude), assumeNotNull(pickup_longitude), 7) AS cell,
    (toHour(pickup_datetime) >= 20 OR toHour(pickup_datetime) < 5) AS after_dark,
    arrayMap(p -> (p.2, p.1), h3ToGeoBoundary(cell)) AS ring
SELECT
    topKIf(1)(pickup_ntaname, after_dark)[1] AS neighborhood,
    [arrayPushBack(ring, ring[1])]::Polygon AS coverage,
    countIf(after_dark) AS night_pickups,
    round(100.0 * night_pickups / count(), 1) AS night_share_pct,
    round(avgIf(fare_amount, after_dark), 2) AS avg_night_fare_usd,
    h3ToString(cell) AS h3_cell
FROM nyc_taxi.trips_small
WHERE pickup_datetime >= '2015-07-01'
  AND pickup_datetime < '2015-10-01'
  AND pickup_longitude BETWEEN -74.05 AND -73.75
  AND pickup_latitude BETWEEN 40.60 AND 40.90
  AND pickup_ntaname != ''
  AND fare_amount BETWEEN 2.5 AND 100
GROUP BY cell
HAVING night_pickups >= 100
ORDER BY night_pickups DESC, h3_cell
LIMIT 64`;

